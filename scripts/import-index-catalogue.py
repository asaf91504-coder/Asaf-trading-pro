"""Import public IVV/IWM holdings CSVs; run with local files, never quote API calls.
Usage: python scripts/import-index-catalogue.py /path/ivv.csv /path/iwm.csv
Holdings are a dated index proxy, not an official constituent certification.
"""
import csv, io, json, pathlib, re, sys
root = pathlib.Path(__file__).resolve().parents[1]
rows, sources, excluded = {}, [], []
for key, path, url in zip(['sp500','russell2000'], sys.argv[1:], ['https://www.ishares.com/us/products/239726/ishares-core-s-p-500-etf/latest-holdings.csv','https://www.ishares.com/us/products/239710/ishares-russell-2000-etf/latest-holdings.csv']):
    raw = pathlib.Path(path).read_text(encoding='utf-8-sig')
    date = next(csv.reader([next(l for l in raw.splitlines() if l.startswith('Fund Holdings as of'))]))[1]
    equities = [r for r in csv.DictReader(io.StringIO(raw[raw.index('Ticker,'):])) if r.get('Asset Class') == 'Equity']
    accepted = set()
    for r in equities:
        symbol = r['Ticker'].strip().replace(' ', '.')
        if not re.fullmatch(r'[A-Z][A-Z0-9]*(?:[.\-][A-Z])?',symbol) or r['Exchange'] == 'NO MARKET (E.G. UNLISTED)' or re.search(r'WARRANT|CONTRA|RESTRI|VESTING',r['Name']):
            excluded.append({'group':key,'ticker':r['Ticker'],'name':r['Name'],'reason':'nonstandard, restricted, warrant or unlisted holding'}); continue
        if symbol in accepted: raise ValueError('Duplicate ticker: '+symbol)
        accepted.add(symbol)
        record = rows.setdefault(symbol, {'symbol':symbol,'name':r['Name'],'type':'stock','groups':[]})
        record['groups'].append(key)
    if not (450 <= len(accepted) <= 550 if key == 'sp500' else 1700 <= len(accepted) <= 2200): raise ValueError('Unexpected catalogue size')
    sources.append({'group':key,'asOf':date,'url':url,'equityRows':len(equities),'listedSymbols':len(accepted)})
if len(sources)!=2: raise ValueError('Provide both IVV and IWM CSV files')
metadata={'basis':'ETF holdings proxy; not official index membership or provider coverage','sources':sources,'excluded':excluded}
(root/'index-stock-catalogue.mjs').write_text('// Generated by scripts/import-index-catalogue.py. Names and symbols only; no prices.\nexport const indexCatalogueMetadata='+json.dumps(metadata,ensure_ascii=False,separators=(',',':'))+';\nexport const indexStocks='+json.dumps(sorted(rows.values(),key=lambda x:x['symbol']),ensure_ascii=False,separators=(',',':'))+';\n')
print(json.dumps({'sources':sources,'uniqueSymbols':len(rows),'excluded':excluded},indent=2))
